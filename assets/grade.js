// Самооценка грейда (/blog/dzhun-midl-ili-senior/): по каждому критерию выбираете
// описание, которое честно про вас; итог — грейд, на который вы стабильно тянете.
(function () {
  "use strict";
  var root = document.getElementById("grade");
  if (!root) return;
  var LEVELS = ["Стажёр", "Junior", "Middle", "Senior"];
  // [критерий, [описание для каждого уровня]]
  var Q = [
    ["Самостоятельность", ["решаю учебные задачи с подробной инструкцией", "решаю понятные задачи сам, но часто спрашиваю, как правильно", "беру задачу с неполным описанием и довожу до продакшена без постоянной помощи", "сам формулирую задачи из проблемы бизнеса и разбиваю их для других"]],
    ["Размер задач", ["одна функция или небольшое исправление", "фича в одном сервисе или модуле за несколько дней", "фича через несколько сервисов, с изменением API и данных", "проект на месяцы, затрагивающий несколько команд"]],
    ["Проектирование", ["пишу код по готовой структуре", "понимаю устройство своего модуля", "проектирую модуль или сервис и обосновываю решения", "проектирую систему целиком с учётом нагрузки, отказов и стоимости"]],
    ["Код-ревью", ["моё ревью не проводят", "мои изменения часто возвращают с существенными замечаниями", "мой код проходит ревью почти без замечаний, ревьюю коллег", "задаю стандарты кода, через мои ревью растут другие"]],
    ["Продакшен и инциденты", ["не работал с продакшеном", "знаю, где смотреть логи, но разбираю сбои с помощью", "сам нахожу и чиню причину инцидента в своей зоне", "веду разбор крупных инцидентов и меняю процессы, чтобы они не повторялись"]],
    ["Тесты и качество", ["пишу тесты, когда просят", "пишу юнит-тесты к своему коду", "выбираю, что и как тестировать, включая интеграционные тесты", "выстраиваю подход к качеству в команде"]],
    ["Наставничество", ["учусь сам", "помогаю стажёрам с простыми вопросами", "регулярно помогаю джунам, онбордю новичков", "развиваю людей, участвую в найме и оценке"]],
    ["Общение с бизнесом", ["получаю задачи от наставника", "уточняю требования у аналитика или тимлида", "обсуждаю требования с продактом и предлагаю варианты", "влияю на продуктовые решения и приоритеты"]],
  ];
  root.innerHTML = Q.map(function (q, i) {
    return '<fieldset class="gr-q"><legend>' + (i + 1) + ". " + q[0] + "</legend>" + q[1].map(function (d, j) {
      return '<label><input type="radio" name="q' + i + '" value="' + j + '"><span>' + d + "</span></label>";
    }).join("") + "</fieldset>";
  }).join("") + '<div class="gr-out" aria-live="polite"></div>';

  function calc() {
    var vals = Q.map(function (_, i) { var x = root.querySelector("[name=q" + i + "]:checked"); return x ? +x.value : null; });
    var done = vals.filter(function (x) { return x !== null; });
    var out = root.querySelector(".gr-out");
    if (done.length < Q.length) { out.innerHTML = "<p>Ответьте на все " + Q.length + " вопросов — осталось " + (Q.length - done.length) + ".</p>"; return; }
    // Грейд — уровень, который закрыт по большинству критериев: нижний квартиль ответов,
    // а не среднее — один сильный навык не делает сеньором.
    var sorted = done.slice().sort(), level = sorted[Math.floor(sorted.length / 4)];
    // Сначала то, что ниже итогового уровня, — это провалы; затем то, что на уровне.
    var name = function (q) { return q[0].toLowerCase(); };
    var gaps = Q.filter(function (_, i) { return vals[i] < level; }).map(name);
    var even = Q.filter(function (_, i) { return vals[i] === level; }).map(name);
    var next = level < 3 ? LEVELS[level + 1] : null;
    out.innerHTML = '<div class="tr-stats sal-stats"><div class="fact"><b>' + LEVELS[level] + "</b><span>грейд, на который вы стабильно тянете по большинству критериев</span></div></div>" +
      (next ? "<p>Чтобы дорасти до " + next + ", " + (gaps.length ? "сначала подтяните то, что ниже вашего уровня: " + gaps.join(", ") + ". Затем — " : "развивайте ") + even.join(", ") + ".</p>" : "<p>Дальше — рост в ширину: архитектура, лидерство или глубокая экспертиза.</p>");
  }
  root.addEventListener("change", calc);
  calc();
})();
